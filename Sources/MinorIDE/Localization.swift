import Foundation

/// Localized UI text. Keys are the English (US) strings; translations live in
/// Resources/<lang>.lproj/Localizable.strings (copied into the app bundle by tools/bundle.sh).
/// Outside the bundle (swift run, tests) the English key is shown.
func L(_ key: String) -> String {
	NSLocalizedString(key, tableName: nil, bundle: .main, value: key, comment: "")
}

/// Localized format string with arguments.
func L(_ key: String, _ args: CVarArg...) -> String {
	String(format: L(key), arguments: args)
}

/// Text with a count, declined by the language's plural rules (Czech: 1 mezera, 2 mezery, 5 mezer).
/// `other` is the English plural and the key, `one` the English singular; both contain the count as %d.
/// Translations come from Localizable.stringsdict, generated by `make l10n`.
func LP(_ other: String, one: String, _ count: Int) -> String {
	if hasPluralTable {
		let format = NSLocalizedString(other, tableName: nil, bundle: .main, value: other, comment: "")
		return String.localizedStringWithFormat(format, count)
	}
	return String(format: count == 1 ? one : other, count) // English rule outside the app bundle
}

private let hasPluralTable = Bundle.main.url(forResource: "Localizable", withExtension: "stringsdict") != nil
