import Foundation

/// Writes `Strings.swift`: typed accessors for every message of the source language, and the source
/// file itself (the built-in English fallback).
nonisolated public enum Generator {
	public static func swift(source: String, catalog: Catalog) -> String {
		let root = Node()
		for key in catalog.messages.keys.sorted() {
			guard let message = catalog.messages[key] else { continue }
			var node = root
			let parts = key.split(separator: ".").map(String.init)
			for part in parts.dropLast() { node = node.child(part) }
			if let last = parts.last { node.messages.append((last, key, message)) }
		}
		var out = "// Generated by `tools/l10n.sh generate` from Resources/Localization/en-US.json. Do not edit.\n\n"
		out += "nonisolated extension L10n {\n\tstatic let englishSource = #\"\"\"\n"
		for line in source.split(separator: "\n", omittingEmptySubsequences: false) {
			out += line.isEmpty ? "\n" : "\t\(line)\n"
		}
		if !source.hasSuffix("\n") { out += "\n" }
		out += "\t\"\"\"#\n}\n\n"
		out += "nonisolated public enum Strings {\n"
		write(root, depth: 1, into: &out)
		out += "}\n"
		return out
	}

	private final class Node {
		var children: [(String, Node)] = []
		var messages: [(name: String, key: String, message: Message)] = []

		func child(_ name: String) -> Node {
			if let found = children.first(where: { $0.0 == name }) { return found.1 }
			let node = Node()
			children.append((name, node))
			return node
		}
	}

	private static func write(_ node: Node, depth: Int, into out: inout String) {
		let tab = String(repeating: "\t", count: depth)
		for (name, message) in node.messages.map({ ($0.name, $0) }) {
			if let note = message.message.note {
				for line in note.split(separator: "\n") { out += "\(tab)/// \(line)\n" }
			}
			out += accessor(name: name, key: message.key, message: message.message, tab: tab)
		}
		for (name, child) in node.children {
			out += "\(tab)nonisolated public enum \(identifier(name)) {\n"
			write(child, depth: depth + 1, into: &out)
			out += "\(tab)}\n"
		}
	}

	private static func accessor(name: String, key: String, message: Message, tab: String) -> String {
		var parameters: [(name: String, format: ParameterFormat)] = []
		for template in message.templates.sorted(by: { $0.segments.count > $1.segments.count }) {
			for p in template.parameters where !parameters.contains(where: { $0.name == p.name }) { parameters.append(p) }
		}
		// Keep the order in which the main text names the parameters.
		let main = (message.text ?? message.plural[.other])?.parameters.map(\.name) ?? []
		parameters.sort { (main.firstIndex(of: $0.name) ?? Int.max, $0.name) < (main.firstIndex(of: $1.name) ?? Int.max, $1.name) }
		if message.isPlural { parameters.removeAll { $0.name == "count" } }

		var signature: [String] = []
		var call: [String] = ["\"\(key)\""]
		var variantType: String?
		if !message.variants.isEmpty {
			let type = upperFirst(name) + "Variant"
			variantType = type
			signature.append("_ variant: \(type)? = nil")
			call.append("variant: variant?.rawValue")
		}
		if message.isPlural {
			signature.append("count: Int")
			call.append("count: count")
		}
		var arguments: [String] = []
		for p in parameters {
			let label = identifier(p.name)
			let (type, value) = switch p.format {
			case .plain: ("some CustomStringConvertible", ".text(String(describing: \(label)))")
			case .number, .bytes: ("some BinaryInteger", ".integer(Int(\(label)))")
			case .percent: ("Double", ".decimal(\(label))")
			case .date, .time: ("Date", ".date(\(label))")
			}
			signature.append("\(label): \(type)")
			arguments.append("\"\(p.name)\": \(value)")
		}
		if !arguments.isEmpty { call.append("[" + arguments.joined(separator: ", ") + "]") }

		var out = ""
		if let variantType {
			let cases = message.variants.keys.sorted().map(identifier).joined(separator: ", ")
			out += "\(tab)nonisolated public enum \(variantType): String, Sendable { case \(cases) }\n"
		}
		let body = "L10n.string(\(call.joined(separator: ", ")))"
		if signature.isEmpty {
			out += "\(tab)public static var \(identifier(name)): String { \(body) }\n"
		} else {
			out += "\(tab)public static func \(identifier(name))(\(signature.joined(separator: ", "))) -> String { \(body) }\n"
		}
		return out
	}

	private static func upperFirst(_ s: String) -> String { s.prefix(1).uppercased() + s.dropFirst() }

	static let keywords: Set<String> = [
		"associatedtype", "class", "deinit", "enum", "extension", "fileprivate", "func", "import", "inout", "internal", "let",
		"open", "operator", "private", "protocol", "public", "rethrows", "static", "struct", "subscript", "typealias", "var",
		"break", "case", "catch", "continue", "default", "defer", "do", "else", "fallthrough", "for", "guard", "if", "in",
		"repeat", "return", "switch", "throw", "throws", "where", "while", "as", "false", "is", "nil", "super", "true", "try",
		"any", "some", "async", "await",
	]
	/// Names that cannot be used even in backticks as a member.
	static let forbidden: Set<String> = ["self", "Self", "Type", "Protocol", "init"]

	static func identifier(_ s: String) -> String { keywords.contains(s) ? "`\(s)`" : s }

	static func isValidSegment(_ s: String) -> Bool {
		guard let first = s.unicodeScalars.first, !forbidden.contains(s) else { return false }
		let letters = CharacterSet(charactersIn: "abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ_")
		let digits = CharacterSet(charactersIn: "0123456789")
		return letters.contains(first) && s.unicodeScalars.allSatisfy { letters.contains($0) || digits.contains($0) }
	}
}
