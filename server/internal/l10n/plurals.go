package l10n

import (
	"fmt"
	"strings"
)

// Plural categories each language must translate (CLDR cardinal rules for integers).
// Czech: one = 1, few = 2–4, other = 0 and 5+ ("many" exists only for decimals, so optional).
var requiredPlurals = map[string][]string{
	"en": {"one", "other"},
	"cs": {"one", "few", "other"},
	"sk": {"one", "few", "other"},
	"pl": {"one", "few", "many", "other"},
	"ru": {"one", "few", "many", "other"},
	"uk": {"one", "few", "many", "other"},
	"hr": {"one", "few", "other"},
	"sl": {"one", "two", "few", "other"},
	"ja": {"other"},
	"ko": {"other"},
	"zh": {"other"},
	"vi": {"other"},
}

// pluralCategories lists all CLDR categories in their canonical order.
var pluralCategories = []string{"zero", "one", "two", "few", "many", "other"}

// RequiredPlurals returns the categories a language must provide ("pt-BR" falls back to "pt").
func RequiredPlurals(lang string) []string {
	if c, ok := requiredPlurals[lang]; ok {
		return c
	}
	if base, _, ok := strings.Cut(lang, "-"); ok {
		if c, ok := requiredPlurals[base]; ok {
			return c
		}
	}
	return []string{"one", "other"}
}

// pluralKey joins a plural key with its category as it appears in .strings files.
func pluralKey(key, category string) string { return key + "|" + category }

// splitPluralKey returns the key and category of a "key|category" entry.
func splitPluralKey(k string) (string, string, bool) {
	i := strings.LastIndexByte(k, '|')
	if i < 0 || !contains(pluralCategories, k[i+1:]) {
		return "", "", false
	}
	return k[:i], k[i+1:], true
}

// expand turns source entries into the .strings entries for a language: plural keys become
// one entry per category, defaulting to the English singular for "one" and plural otherwise.
func expand(source []Entry, lang string) []Entry {
	var out []Entry
	for _, e := range source {
		if !e.Plural {
			out = append(out, e)
			continue
		}
		for _, c := range RequiredPlurals(lang) {
			v := e.Key
			if c == "one" {
				v = e.One
			}
			out = append(out, Entry{Key: pluralKey(e.Key, c), Value: v, Files: e.Files})
		}
	}
	return out
}

// Stringsdict renders the plural entries of a language as Localizable.stringsdict, or "" when
// there are none. The count is the format's first argument (%d in every form).
func Stringsdict(entries []Entry) string {
	forms := map[string]map[string]string{}
	var keys []string
	for _, e := range entries {
		key, cat, ok := splitPluralKey(e.Key)
		if !ok {
			continue
		}
		if forms[key] == nil {
			forms[key] = map[string]string{}
			keys = append(keys, key)
		}
		forms[key][cat] = e.Value
	}
	if len(keys) == 0 {
		return ""
	}
	var b strings.Builder
	b.WriteString(`<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<!-- Generated by "make l10n" from "key|category" entries in Localizable.strings. Do not edit. -->
<plist version="1.0">
<dict>
`)
	for _, key := range keys {
		fmt.Fprintf(&b, "\t<key>%s</key>\n\t<dict>\n", xmlEscape(key))
		b.WriteString("\t\t<key>NSStringLocalizedFormatKey</key>\n\t\t<string>%#@count@</string>\n")
		b.WriteString("\t\t<key>count</key>\n\t\t<dict>\n")
		b.WriteString("\t\t\t<key>NSStringFormatSpecTypeKey</key>\n\t\t\t<string>NSStringPluralRuleType</string>\n")
		b.WriteString("\t\t\t<key>NSStringFormatValueTypeKey</key>\n\t\t\t<string>d</string>\n")
		for _, c := range pluralCategories {
			if v, ok := forms[key][c]; ok {
				fmt.Fprintf(&b, "\t\t\t<key>%s</key>\n\t\t\t<string>%s</string>\n", c, xmlEscape(v))
			}
		}
		b.WriteString("\t\t</dict>\n\t</dict>\n")
	}
	b.WriteString("</dict>\n</plist>\n")
	return b.String()
}

func xmlEscape(s string) string {
	return strings.NewReplacer("&", "&amp;", "<", "&lt;", ">", "&gt;").Replace(s)
}

// subset reports whether every placeholder type of a also occurs in b (a plural form may omit
// the number, e.g. "jedna mezera", but must not add or change arguments).
func subset(a, b []string) bool {
	left := map[string]int{}
	for _, x := range b {
		left[x]++
	}
	for _, x := range a {
		if left[x] == 0 {
			return false
		}
		left[x]--
	}
	return true
}
