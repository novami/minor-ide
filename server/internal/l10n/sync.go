package l10n

import (
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strings"
)

const englishHeader = `/* English (US) — generated by "make l10n" from L("…") calls in Sources/. Do not edit:
   change the text in the Swift source and run "make l10n" again. */
`

func translationHeader(lang string) string {
	// The header must not contain the TODO marker itself: its "*/" would end this comment early.
	return fmt.Sprintf(`/* %s translation of MinorIDE. Keys are the English texts.
   Entries marked "TODO translate" still show English: translate the value and delete the marker.
   Run "make l10n" after changing source strings, "make l10n-check" to verify. */
`, lang)
}

// Report describes the state of one language after Sync.
type Report struct {
	Lang                string
	Added, Todo         int
	Obsolete            []string
	PlaceholderMismatch []string
}

// Languages lists the *.lproj directories under resources, English first.
func Languages(resources string) ([]string, error) {
	dirs, err := filepath.Glob(filepath.Join(resources, "*.lproj"))
	if err != nil {
		return nil, err
	}
	var langs []string
	for _, d := range dirs {
		lang := strings.TrimSuffix(filepath.Base(d), ".lproj")
		if lang != "en" {
			langs = append(langs, lang)
		}
	}
	sort.Strings(langs)
	return append([]string{"en"}, langs...), nil
}

func stringsPath(resources, lang string) string {
	return filepath.Join(resources, lang+".lproj", "Localizable.strings")
}

// Sync regenerates English from the sources and brings every other language in line:
// missing keys are added with the English text and a TODO marker, existing translations
// are kept, obsolete keys (no longer in the sources) are dropped and reported.
// With create set, a new language directory is created first.
func Sync(sources, resources string, create string) ([]Report, error) {
	english, err := Extract(sources)
	if err != nil {
		return nil, err
	}
	if err := os.MkdirAll(filepath.Join(resources, "en.lproj"), 0o755); err != nil {
		return nil, err
	}
	if err := os.WriteFile(stringsPath(resources, "en"), []byte(Format(englishHeader, english)), 0o644); err != nil {
		return nil, err
	}
	if create != "" {
		if err := os.MkdirAll(filepath.Join(resources, create+".lproj"), 0o755); err != nil {
			return nil, err
		}
	}
	langs, err := Languages(resources)
	if err != nil {
		return nil, err
	}
	var reports []Report
	for _, lang := range langs[1:] {
		existing := map[string]Entry{}
		if data, err := os.ReadFile(stringsPath(resources, lang)); err == nil {
			parsed, err := Parse(string(data))
			if err != nil {
				return nil, fmt.Errorf("%s: %v", lang, err)
			}
			for _, e := range parsed {
				existing[e.Key] = e
			}
		}
		r := Report{Lang: lang}
		out := make([]Entry, 0, len(english))
		for _, en := range english {
			e, ok := existing[en.Key]
			if !ok {
				e = Entry{Key: en.Key, Value: en.Value, Todo: true}
				r.Added++
			}
			delete(existing, en.Key)
			e.Files = en.Files
			if e.Todo {
				r.Todo++
			} else if fmt.Sprint(Placeholders(e.Value)) != fmt.Sprint(Placeholders(en.Key)) {
				r.PlaceholderMismatch = append(r.PlaceholderMismatch, en.Key)
			}
			out = append(out, e)
		}
		for k := range existing {
			r.Obsolete = append(r.Obsolete, k)
		}
		sort.Strings(r.Obsolete)
		if err := os.WriteFile(stringsPath(resources, lang), []byte(Format(translationHeader(lang), out)), 0o644); err != nil {
			return nil, err
		}
		reports = append(reports, r)
	}
	return reports, nil
}

// Check verifies without writing: English is up to date with the sources, every language has
// every key with matching placeholders, and required languages have no untranslated entries.
func Check(sources, resources string, required []string) []string {
	var problems []string
	english, err := Extract(sources)
	if err != nil {
		return []string{err.Error()}
	}
	want := Format(englishHeader, english)
	if got, _ := os.ReadFile(stringsPath(resources, "en")); string(got) != want {
		problems = append(problems, `en: out of date with the sources, run "make l10n"`)
	}
	langs, err := Languages(resources)
	if err != nil {
		return []string{err.Error()}
	}
	for _, lang := range required {
		if !contains(langs, lang) {
			problems = append(problems, lang+": required language is missing")
		}
	}
	for _, lang := range langs[1:] {
		data, err := os.ReadFile(stringsPath(resources, lang))
		if err != nil {
			problems = append(problems, fmt.Sprintf("%s: %v", lang, err))
			continue
		}
		parsed, err := Parse(string(data))
		if err != nil {
			problems = append(problems, fmt.Sprintf("%s: %v", lang, err))
			continue
		}
		have := map[string]Entry{}
		for _, e := range parsed {
			have[e.Key] = e
		}
		isRequired := contains(required, lang)
		for _, en := range english {
			e, ok := have[en.Key]
			switch {
			case !ok:
				problems = append(problems, fmt.Sprintf(`%s: missing %q (run "make l10n")`, lang, en.Key))
			case e.Todo && isRequired:
				problems = append(problems, fmt.Sprintf("%s: not translated %q", lang, en.Key))
			case !e.Todo && fmt.Sprint(Placeholders(e.Value)) != fmt.Sprint(Placeholders(en.Key)):
				problems = append(problems, fmt.Sprintf("%s: placeholders differ in %q → %q", lang, en.Key, e.Value))
			}
		}
	}
	return problems
}
